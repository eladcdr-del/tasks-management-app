const ALL = Object.values(CORPUS).flat();

describe('negative corpus: no date, no time, no priority, title intact', () => {
  it('has at least 100 real-world inputs, none repeated', () => {
    expect(ALL.length).toBeGreaterThanOrEqual(100);
    expect(new Set(ALL).size).toBe(ALL.length);
  });

  for (const [group, inputs] of Object.entries(CORPUS)) {
    it.each(inputs)(`${group}: %s`, (input) => {
      const r = parseQuickAdd(input, NOW);
      expect(r.scheduledFor).toBeUndefined();
      expect(r.dueDate).toBeUndefined();
      expect(r.dueTime).toBeUndefined();
      expect(r.priority).toBeUndefined();
      expect(r.hardDeadline).toBeUndefined();
      expect(r.title).toBe(input);
      expect(r.recurrence).toBeUndefined();
      expect(r.matches.every((m) => m.kind === 'category')).toBe(true);
    });
  }
});
